<?php
declare(strict_types=1);

use App\Config\Database;
use App\Controllers\AttendanceController;
use App\Controllers\AuthController;
use App\Controllers\BillingConfigurationController;
use App\Controllers\ClassController;
use App\Controllers\DashboardController;
use App\Controllers\DebtController;
use App\Controllers\EnrollmentController;
use App\Controllers\MembershipController;
use App\Controllers\NotificationController;
use App\Controllers\PaymentController;
use App\Controllers\PrivateClassController;
use App\Controllers\ProfessorController;
use App\Controllers\StudentController;
use App\Core\Router;
use App\Models\AttendanceModel;
use App\Models\BillingConfigurationModel;
use App\Models\ClassModel;
use App\Models\DashboardModel;
use App\Models\DebtModel;
use App\Models\EnrollmentModel;
use App\Models\MembershipModel;
use App\Models\NotificationModel;
use App\Models\PaymentModel;
use App\Models\PrivateClassModel;
use App\Models\ProfessorModel;
use App\Models\StudentModel;
use App\Models\UserModel;

$db = Database::connect();
$router = new Router();
$auth = new AuthController(new UserModel($db));
$students = new StudentController(new StudentModel($db));
$memberships = new MembershipController(new MembershipModel($db));
$payments = new PaymentController(new PaymentModel($db));
$debts = new DebtController(new DebtModel($db));
$attendance = new AttendanceController(new AttendanceModel($db));
$dashboard = new DashboardController(new DashboardModel($db));
$privateClasses = new PrivateClassController(new PrivateClassModel($db));
$notifications = new NotificationController(new NotificationModel($db));
$classes = new ClassController(new ClassModel($db));
$enrollments = new EnrollmentController(new EnrollmentModel($db));
$professors = new ProfessorController(new ProfessorModel($db));
$billingConfiguration = new BillingConfigurationController(new BillingConfigurationModel($db));

$router->add('POST', '~^/login$~', [$auth, 'login'], false);
$router->add('POST', '~^/logout$~', [$auth, 'logout']);
$router->add('GET', '~^/students$~', [$students, 'index'], true, 'students.read');
$router->add('POST', '~^/students$~', [$students, 'store'], true, 'students.write');
$router->add('GET', '~^/students/me$~', [$students, 'mine'], true, 'students.read_own');
$router->add('GET', '~^/students/assigned$~', [$students, 'assigned'], true, 'students.read_assigned');
$router->add('GET', '~^/students/(?P<id>\d+)$~', [$students, 'show'], true, 'students.read');
$router->add('PUT', '~^/students/(?P<id>\d+)$~', [$students, 'update'], true, 'students.write');
$router->add('DELETE', '~^/students/(?P<id>\d+)$~', [$students, 'destroy'], true, 'students.deactivate');
$router->add('GET', '~^/memberships$~', [$memberships, 'index'], true, 'tariffs.read');
$router->add('POST', '~^/memberships$~', [$memberships, 'store'], true, 'tariffs.write');
$router->add('PUT', '~^/memberships/(?P<id>\d+)$~', [$memberships, 'update'], true, 'tariffs.write');
$router->add('GET', '~^/billing-configuration$~', [$billingConfiguration, 'show'], true, 'billing_config.read');
$router->add('PUT', '~^/billing-configuration$~', [$billingConfiguration, 'update'], true, 'billing_config.write');
$router->add('GET', '~^/payments$~', [$payments, 'index'], true, 'payments.read');
$router->add('GET', '~^/payments/me$~', [$payments, 'mine'], true, 'payments.read_own');
$router->add('POST', '~^/payments$~', [$payments, 'store'], true, 'payments.create');
$router->add('POST', '~^/payments/(?P<id>\d+)/cancel$~', [$payments, 'cancel'], true, 'payments.cancel');
$router->add('GET', '~^/debts$~', [$debts, 'index'], true, 'debts.read');
$router->add('GET', '~^/debts/me$~', [$debts, 'mine'], true, 'debts.read_own');
$router->add('GET', '~^/attendance$~', [$attendance, 'index'], true, 'attendance.read');
$router->add('GET', '~^/attendance/assigned$~', [$attendance, 'assigned'], true, 'attendance.read_assigned');
$router->add('GET', '~^/attendance/me$~', [$attendance, 'mine'], true, 'attendance.read_own');
$router->add('POST', '~^/attendance$~', [$attendance, 'store'], true, 'attendance.write_assigned');
$router->add('PUT', '~^/attendance/(?P<id>\d+)$~', [$attendance, 'update'], true, 'attendance.write_assigned');
$router->add('GET', '~^/dashboard$~', [$dashboard, 'summary'], true, 'reports.read');
$router->add('GET', '~^/private-classes$~', [$privateClasses, 'index'], true, 'private_classes.read');
$router->add('GET', '~^/private-classes/me$~', [$privateClasses, 'mine'], true, 'private_classes.read_own');
$router->add('POST', '~^/private-classes$~', [$privateClasses, 'store'], true, 'private_classes.create');
$router->add('GET', '~^/classes$~', [$classes, 'index'], true, 'classes.read');
$router->add('GET', '~^/classes/assigned$~', [$classes, 'assigned'], true, 'classes.read_assigned');
$router->add('GET', '~^/classes/me$~', [$classes, 'mine'], true, 'classes.read_own');
$router->add('GET', '~^/classes/assigned/students$~', [$classes, 'assignedStudents'], true, 'students.read_assigned');
$router->add('GET', '~^/class-enrollments$~', [$enrollments, 'index'], true, 'enrollments.read');
$router->add('GET', '~^/class-enrollments/assigned$~', [$enrollments, 'assigned'], true, 'enrollments.read_assigned');
$router->add('GET', '~^/class-enrollments/me$~', [$enrollments, 'mine'], true, 'enrollments.read_own');
$router->add('POST', '~^/class-enrollments$~', [$enrollments, 'store'], true, 'enrollments.write');
$router->add('DELETE', '~^/class-enrollments/(?P<id>\d+)$~', [$enrollments, 'destroy'], true, 'enrollments.write');
$router->add('GET', '~^/professors$~', [$professors, 'index'], true, 'professors.read');
$router->add('GET', '~^/notifications$~', [$notifications, 'index'], true, 'notifications.read_own');
$router->add('PATCH', '~^/notifications/(?P<id>\d+)/read$~', [$notifications, 'markRead'], true, 'notifications.mark_own');

$route = $_GET['route'] ?? '/';
if (!is_string($route) || !str_starts_with($route, '/') || str_contains($route, '..')) {
    http_response_code(400);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode(['error' => 'Ruta inválida.'], JSON_UNESCAPED_UNICODE);
    return;
}
$router->dispatch($_SERVER['REQUEST_METHOD'] ?? 'GET', $route);
